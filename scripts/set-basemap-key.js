// Writes the CARTO basemap key into both builds, from carto-key.txt.
//
// The key must not live in a tracked file: it ships publicly inside the
// extension either way, but there's no reason to hand it to anyone grepping
// GitHub. carto-key.txt and the generated basemap-key.js are both gitignored,
// so a clone builds fine (watermarked tiles) and a release build is keyed.
//
//   node scripts/set-basemap-key.js            # from carto-key.txt
//   node scripts/set-basemap-key.js <key>      # explicit
//   node scripts/set-basemap-key.js --clear    # blank it again
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const BUILDS = ["extension", "edge-extension"];
const arg = process.argv[2];

let key = "";
if (arg === "--clear") {
  key = "";
} else if (arg) {
  key = arg.trim();
} else {
  const file = path.join(ROOT, "carto-key.txt");
  if (!fs.existsSync(file)) {
    console.error("No carto-key.txt and no key given.");
    console.error("Get a free key at https://carto.com/basemaps/apikey/ then:");
    console.error("  echo YOUR_KEY > carto-key.txt && node scripts/set-basemap-key.js");
    process.exit(1);
  }
  key = fs.readFileSync(file, "utf8").trim();
}

for (const build of BUILDS) {
  const out = path.join(ROOT, build, "basemap-key.js");
  fs.writeFileSync(out, `// Generated by scripts/set-basemap-key.js — not committed.\n` +
    `window.MKPM_BASEMAP_KEY = ${JSON.stringify(key)};\n`);
  console.log(`${key ? "keyed" : "cleared"}  ${build}/basemap-key.js`);
}

if (!key) console.log("\nTiles will carry the CARTO watermark until a key is set.");
